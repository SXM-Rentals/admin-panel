import type { AdminProvider, ProviderPayoutAccount, VehicleDocument } from '@/types';
import { DUTCH_TOWNS, FRENCH_TOWNS, daysAgo, seeded, between } from './seed';

const rng = seeded(4021);

// The paperwork a business itself has to file, as opposed to the paperwork for
// each individual vehicle. Same shape, reviewed the same way.
function docs(
  registration: VehicleDocument['status'],
  insurance: VehicleDocument['status'],
  reason?: string,
): VehicleDocument[] {
  return [
    {
      kind: 'registration',
      status: registration,
      fileName: 'chamber-of-commerce-extract.pdf',
      uploadedAt: daysAgo(between(rng, 30, 400)),
      reason: registration === 'rejected' ? reason : undefined,
    },
    {
      kind: 'insurance',
      status: insurance,
      fileName: 'fleet-liability-policy.pdf',
      uploadedAt: daysAgo(between(rng, 20, 300)),
      expiresAt: daysAgo(-between(rng, 40, 500)),
      reason: insurance === 'rejected' ? reason : undefined,
    },
  ];
}

function payout(
  status: ProviderPayoutAccount['status'],
  country: string,
  outstanding: string[] = [],
): ProviderPayoutAccount {
  return {
    stripeAccountId: status === 'not_started' ? undefined : `acct_${between(rng, 100000, 999999)}SXM`,
    status,
    outstanding,
    payoutsEnabled: status === 'active',
    country,
  };
}

